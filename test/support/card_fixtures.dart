import 'package:rinde_mobile/features/cards/data/card_models.dart';

/// Una tarjeta con la forma EXACTA de GET /cards de QA (23-nov-2026, cuenta sintética).
Map<String, dynamic> cardJson({
  String id = '41ced642-66c1-4615-85a6-8d38152f9d44',
  String name = 'Visa Clásica ••4242',
  String network = 'visa',
  String tier = 'clasica',
  String last4 = '4242',
  num limit = 2000000,
  num used = 500000,
  num? available,
  int paymentDay = 15,
  int? cutoffDay = 30,
  num? statementTotal,
  String? statementDueDate,
  String? nextPaymentDate = '2026-12-15',
  int daysToPayment = 22,
  bool paidThisCycle = false,
  String? paidDueDate,
  num paidAmount = 0,
  int? expiryMonth,
  int? expiryYear,
  Map<String, dynamic>? expiry,
}) => {
  'id': id,
  'name': name,
  'network': network,
  'tier': tier,
  'last4': last4,
  'limit': limit,
  'used': used,
  'available': available ?? limit - used,
  'paymentDay': paymentDay,
  'cutoffDay': cutoffDay,
  'statementTotal': statementTotal,
  'statementDueDate': statementDueDate,
  'nextPaymentDate': nextPaymentDate,
  'daysToPayment': daysToPayment,
  'paidThisCycle': paidThisCycle,
  'paidDueDate': paidDueDate,
  'paidAmount': paidAmount,
  'reminderSentFor': null,
  'expiryMonth': expiryMonth,
  'expiryYear': expiryYear,
  'expiry': expiry,
  'expiryNotified': const <Object>[],
};

CreditCard cardOfJson([Map<String, dynamic>? json]) => CreditCard.fromJson(json ?? cardJson());

CreditCard creditCard({
  String id = 't1',
  String name = 'Visa Clásica ••4242',
  String network = 'visa',
  String tier = 'clasica',
  String last4 = '4242',
  num limit = 2000000,
  num used = 500000,
  num? available,
  int daysToPayment = 22,
  bool paidThisCycle = false,
  String? nextPaymentDate = '2026-12-15',
  num? statementTotal,
  String? statementDueDate,
  Map<String, dynamic>? expiry,
  int? expiryMonth,
  int? expiryYear,
  int? cutoffDay = 30,
}) => CreditCard.fromJson(
  cardJson(
    id: id,
    name: name,
    network: network,
    tier: tier,
    last4: last4,
    limit: limit,
    used: used,
    available: available,
    daysToPayment: daysToPayment,
    paidThisCycle: paidThisCycle,
    nextPaymentDate: nextPaymentDate,
    statementTotal: statementTotal,
    statementDueDate: statementDueDate,
    expiry: expiry,
    expiryMonth: expiryMonth,
    expiryYear: expiryYear,
    cutoffDay: cutoffDay,
  ),
);
